-- Segemnt customer into new, returning and loyal based on their total number of previous purchase and show the count of each segment.

select 
case 
    when previous_purchases = '0' then 'New Customer'
    when previous_purchases between 1 and 15 then 'Returning Customer'
else 'Loyal Customer'
end as customer_segment,
count(*) as customer_count
from shopping_data
group by case 
    when previous_purchases = '0' then 'New Customer'
    when previous_purchases between 1 and 15 then 'Returning Customer'
else 'Loyal Customer'
end;

