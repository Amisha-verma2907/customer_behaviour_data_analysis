-- Are customers who are repeat buyers (more than 5 previous purchases) are likely to subscribes?

select 
       case
       when previous_purchases > 5 then 'Repeat buyers'
       else 'Normal Buyers'
       end as customer_type,
       subscription_status,
       count(*) as customer_count,
       count(*) * 100.0 /sum(count(*)) over (partition by case
       when previous_purchases > 5 then 'Repeat buyers'
       else 'Normal Buyers'
       end ) as percent
from shopping_data
group by case
		 when previous_purchases > 5 then 'Repeat Buyers'
         else 'Normal Buyers'
         end, subscription_status;
         
